"""Reverse-proxy route synchronisation for the per-router LuCI vhosts.

Two moving parts:

* **nginx driver** - renders one include file plus a shared auth snippet that nginx pulls
  in from the *http* context, and reloads nginx only when the rendered bytes actually
  changed. 100+ routers means 100+ server blocks, so the file is written atomically
  (tmp file + os.replace) - a concurrent reload must never be able to read half a config.
* **caddy driver** - drives the Caddy admin API with httpx, one route per router carrying
  "@id: tg:<router_id>" so a sync is an idempotent upsert + delete-stale.

Both drivers keep last_error up to date (read by GET /api/v1/stats) and never raise
into the monitor loop: a broken proxy must not stop tunnel bookkeeping.

Why the router id lives in an nginx variable
--------------------------------------------
auth_request cannot take arguments, and a shared location cannot know which vhost it
belongs to. So each server block sets $tg_router and the single shared snippet builds the
subrequest URL from it:

    location = /__tg/auth { internal;
        proxy_pass http://127.0.0.1:8080/__tg/auth?router_id=$tg_router&uri=$request_uri; }

One snippet for the whole fleet instead of 100 copies, and the id is never attacker
controlled (it is written into the config by this module, not read from a header).
"""

