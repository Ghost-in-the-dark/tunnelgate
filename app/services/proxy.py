"""Reverse-proxy route synchronisation for the per-router LuCI vhosts.

Two moving parts:

* **nginx driver** - renders one include file plus a shared auth snippet that nginx pulls
  in from the *http* context, and reloads nginx only when the rendered bytes actually
  changed. 100+ routers means 100+ server blocks, so the file is written atomically
  (tmp file + os.replace) - a concurrent reload must never be able to read half a config.
* **caddy driver** - drives the Caddy admin API with httpx, one route per router carrying
  "@id: tg:<router_id>" so a sync is an idempotent upsert + delete-stale.

Both drivers keep last_error up to date (read by GET /api/v1/stats) and never raise
into the monitor loop: a broken proxy must not stop tunnel bookkeeping.

Why the router id lives in an nginx variable
--------------------------------------------
auth_request cannot take arguments, and a shared location cannot know which vhost it
belongs to. So each server block sets $tg_router and the single shared snippet builds the
subrequest URL from it:

    location = /__tg/auth { internal;
        proxy_pass http://127.0.0.1:8080/__tg/auth?router_id=$tg_router&uri=$request_uri; }

One snippet for the whole fleet instead of 100 copies, and the id is never attacker
controlled (it is written into the config by this module, not read from a header).
"""

from __future__ import annotations

import asyncio
import contextlib
import hashlib
import json
import logging
import os
import re
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any
from urllib.parse import quote, urlsplit

import httpx

from ..config import get_settings, utcnow

log = logging.getLogger("tunnelgate.proxy")

# Router ids are uuid4 hex, slugs match config.SLUG_RE. Both are interpolated into an
# nginx config that nginx (root) later parses, so they are re-validated here: a single
# quote or newline smuggled into a slug would otherwise inject nginx directives.
_SAFE_TOKEN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._:-]{0,62}$")

GENERATED_MARKER = "# GENERATED by TunnelGate"

DEFAULT_TLS_CERT = "/etc/tunnelgate/tls/fullchain.pem"
DEFAULT_TLS_KEY = "/etc/tunnelgate/tls/privkey.pem"

DEFAULT_RELOAD_TIMEOUT = 20.0
DEFAULT_CLIENT_MAX_BODY = "64m"
CADDY_ROUTE_PREFIX = "tg:"


class ProxyError(RuntimeError):
    """Raised internally; ProxyManager turns it into last_error instead of a crash."""


# --------------------------------------------------------------------------- route specs
@dataclass(frozen=True, slots=True)
class RouteSpec:
    """The minimum a reverse proxy needs to publish one router's LuCI."""

    router_id: str
    slug: str
    port: int
    bind_address: str


def load_routes(db) -> list[RouteSpec]:
    """Read every router that currently owns a tunnel port, sorted by slug.

    pending routers are excluded because no key was handed out yet (the vhost could only
    ever answer 502) and revoked routers because their port was released. Offline routers
    keep their vhost on purpose: the route must survive a reboot of the device instead of
    flapping in and out of the proxy config every few seconds.
    """
    from sqlalchemy import select

    from ..models import STATUS_PENDING, STATUS_REVOKED, Router

    stmt = (
        select(Router)
        .where(Router.remote_port.is_not(None))
        .where(Router.status.not_in((STATUS_PENDING, STATUS_REVOKED)))
        .order_by(Router.slug)
    )
    specs: list[RouteSpec] = []
    for router in db.scalars(stmt):
        if router.remote_port is None:
            continue
        spec = RouteSpec(
            router_id=str(router.id),
            slug=str(router.slug),
            port=int(router.remote_port),
            bind_address=(router.bind_address or get_settings().bind_address or "127.0.0.1"),
        )
        if not _SAFE_TOKEN.match(spec.router_id) or not _SAFE_TOKEN.match(spec.slug):
            log.warning(
                "skipping router %r: id/slug is not safe to interpolate into nginx config",
                router.slug,
            )
            continue
        specs.append(spec)
    return specs


# --------------------------------------------------------------------------- settings glue
def _tls_cert_path(settings) -> str:
    return str(
        getattr(settings, "tls_cert_path", None)
        or os.environ.get("TUNNELGATE_TLS_CERT")
        or DEFAULT_TLS_CERT
    )


def _tls_key_path(settings) -> str:
    return str(
        getattr(settings, "tls_key_path", None)
        or os.environ.get("TUNNELGATE_TLS_KEY")
        or DEFAULT_TLS_KEY
    )


def _reload_timeout(settings) -> float:
    raw = getattr(settings, "proxy_reload_timeout", None) or os.environ.get(
        "TUNNELGATE_PROXY_RELOAD_TIMEOUT"
    )
    try:
        return float(raw) if raw else DEFAULT_RELOAD_TIMEOUT
    except (TypeError, ValueError):
        return DEFAULT_RELOAD_TIMEOUT


def _client_max_body(settings) -> str:
    return str(
        getattr(settings, "proxy_client_max_body", None)
        or os.environ.get("TUNNELGATE_PROXY_CLIENT_MAX_BODY")
        or DEFAULT_CLIENT_MAX_BODY
    )


def panel_endpoint(settings) -> tuple[str, str]:
    """Split settings.panel_url into (scheme, host:port) for proxy_pass."""
    parts = urlsplit(str(settings.panel_url).strip())
    if parts.scheme not in ("http", "https") or not parts.hostname:
        raise ProxyError(f"TUNNELGATE_PANEL_URL is not an http(s) URL: {settings.panel_url!r}")
    host = parts.hostname
    if ":" in host:  # IPv6 literal
        host = f"[{host}]"
    netloc = f"{host}:{parts.port}" if parts.port else host
    return parts.scheme, netloc


def auth_snippet_path(routes_path: str | Path) -> Path:
    """Where the shared auth_request snippet lives (next to the routes include)."""
    path = Path(routes_path)
    return path.with_name(path.stem + ".auth" + path.suffix)


def router_url(settings, slug: str) -> str:
    return f"https://{slug}.{settings.host_suffix}"


# --------------------------------------------------------------------------- nginx render
def render_nginx_auth_snippet(settings) -> str:
    """The shared snippet: one copy, included by every per-router vhost."""
    scheme, netloc = panel_endpoint(settings)
    # The browser-facing login page lives on the panel hostname, not on router hostnames.
    panel_public = str(getattr(settings, "panel_host", "") or netloc)
    return f"""\
{GENERATED_MARKER} - DO NOT EDIT.
# Shared auth_request + login redirect, included by every per-router vhost.
#
# auth_request cannot carry arguments and a shared location does not know which vhost it
# is running for, so each server block sets $tg_router / $tg_slug and this single snippet
# builds the subrequest URL from them.
location = /__tg/auth {{
    internal;

    proxy_pass {scheme}://{netloc}/__tg/auth?router_id=$tg_router&uri=$request_uri;
    proxy_method GET;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header Host $host;
    proxy_set_header X-Original-URI $request_uri;
    proxy_set_header X-Tg-Router $tg_router;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_connect_timeout 5s;
    proxy_read_timeout 10s;
    proxy_send_timeout 10s;
}}

# Reached through "error_page 401 = @tg_login". We redirect instead of returning the
# panel's JSON error because the visitor is a human with a browser.
location @tg_login {{
    return 302 {scheme}://{panel_public}/login?router=$tg_slug&next=$request_uri;
}}
"""


def render_nginx(routes: list[RouteSpec], settings) -> str:
    """Render the full include file: map + one server block per router.

    Pure function - the unit tests compare strings, so no I/O happens here.
    """
    suffix = settings.host_suffix
    cert = _tls_cert_path(settings)
    key = _tls_key_path(settings)
    panel_endpoint(settings)  # validates TUNNELGATE_PANEL_URL before rendering
    snippet = auth_snippet_path(settings.proxy_routes_path)
    body_limit = _client_max_body(settings)

    out: list[str] = [
        f"{GENERATED_MARKER} - DO NOT EDIT.",
        "# Rewritten by app/services/proxy.py whenever the router/port set changes.",
        "# Include from the nginx *http* context, e.g. in the panel vhost file:",
        f"#     include {settings.proxy_routes_path};",
        "#",
        "# One server block per router that owns a tunnel port. Routers in status pending",
        "# (no key handed out yet) and revoked (key destroyed, port released) are absent on",
        "# purpose: their vhost could only answer 502. Offline routers keep their vhost so a",
        "# rebooted device reappears without the route flapping.",
        "#",
        "# The interactive web console has NO per-router vhost: it is served by",
        "# console.<host_suffix> in deploy/nginx/tunnelgate.conf, because only the",
        "# /__tg/auth subrequest can bind a panel session to a router id.",
        "#",
        "# This file declares its own map target ($tg_connection_upgrade). nginx allows one",
        "# map per target variable, and deploy/nginx/tunnelgate.conf uses the conventional",
        "# $connection_upgrade name for the panel/console blocks - do not merge the two.",
        "",
        "map $http_upgrade $tg_connection_upgrade {",
        "    default upgrade;",
        "    ''      close;",
        "}",
        "",
    ]

    if not routes:
        out.append("# No routers currently have an allocated tunnel port.")
        out.append("")

    for spec in routes:
        host = f"{spec.slug}.{suffix}"
        out.extend(
            [
                f"# ---------------------------------------------------------------- {spec.slug}",
                f"# router {spec.router_id} -> http://{spec.bind_address}:{spec.port}",
                "server {",
                "    listen 443 ssl;",
                "    listen [::]:443 ssl;",
                "    http2 on;",
                f"    server_name {host};",
                "",
                f"    ssl_certificate     {cert};",
                f"    ssl_certificate_key {key};",
                "    ssl_protocols TLSv1.2 TLSv1.3;",
                "    ssl_prefer_server_ciphers off;",
                "    ssl_session_cache shared:SSL:10m;",
                "    ssl_session_timeout 1d;",
                "    ssl_session_tickets off;",
                "",
                "    # LuCI firmware uploads are large; the 1m default would answer 413.",
                f"    client_max_body_size {body_limit};",
                "",
                f"    set $tg_router '{spec.router_id}';",
                f"    set $tg_slug '{spec.slug}';",
                "",
                f"    include {snippet};",
                "",
                "    location / {",
                "        auth_request /__tg/auth;",
                "        error_page 401 = @tg_login;",
                "",
                f"        proxy_pass http://{spec.bind_address}:{spec.port};",
                "        proxy_http_version 1.1;",
                "",
                "        proxy_set_header Host              $host;",
                "        proxy_set_header X-Real-IP         $remote_addr;",
                "        proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;",
                "        proxy_set_header X-Forwarded-Proto $scheme;",
                "        proxy_set_header X-Forwarded-Host  $host;",
                "        proxy_set_header X-Forwarded-Port  $server_port;",
                "        proxy_set_header X-Tg-Router       $tg_router;",
                "",
                "        # LuCI uses websockets for ubus notifications; the tunnel is plain HTTP.",
                "        proxy_set_header Upgrade    $http_upgrade;",
                "        proxy_set_header Connection $tg_connection_upgrade;",
                "",
                "        proxy_read_timeout    300s;",
                "        proxy_send_timeout    300s;",
                "        proxy_connect_timeout 10s;",
                "        # Long-polling ubus calls and streamed output must not be buffered.",
                "        proxy_buffering         off;",
                "        proxy_request_buffering off;",
                "    }",
                "",
                '    add_header Strict-Transport-Security "max-age=31536000" always;',
                '    add_header X-Content-Type-Options "nosniff" always;',
                '    add_header X-Robots-Tag "noindex, nofollow" always;',
                "}",
                "",
            ]
        )
    return "\n".join(out)


# --------------------------------------------------------------------------- caddy render
def render_caddy_route(spec: RouteSpec, settings) -> dict[str, Any]:
    """The JSON equivalent of an nginx auth_request vhost, as Caddy route objects.

    Caddy's Caddyfile forward_auth is sugar over a reverse_proxy whose handle_response
    block inspects the subrequest status: 2xx copies the identity header and lets the next
    handler run, anything else returns the subrequest response (401 -> browser). The admin
    API speaks the expanded form, so this builds exactly that.
    """
    host = f"{spec.slug}.{settings.host_suffix}"
    scheme, netloc = panel_endpoint(settings)
    panel_public = str(getattr(settings, "panel_host", "") or netloc)
    auth_uri = f"/__tg/auth?router_id={spec.router_id}&uri={{http.request.uri}}"
    login = f"{scheme}://{panel_public}/login?router={{http.request.host}}"
    return {
        "@id": f"{CADDY_ROUTE_PREFIX}{spec.router_id}",
        "match": [{"host": [host]}],
        "handle": [
            {
                "handler": "reverse_proxy",
                "upstreams": [{"dial": netloc}],
                "rewrite": {"method": "GET", "uri": auth_uri},
                "headers": {
                    "request": {
                        "set": {
                            "X-Forwarded-Method": ["{http.request.method}"],
                            "X-Forwarded-Uri": ["{http.request.uri}"],
                            "X-Tg-Router": [spec.router_id],
                        }
                    }
                },
                "handle_response": [
                    {
                        "match": {"status_code": [401, 403]},
                        "routes": [
                            {
                                "handle": [
                                    {
                                        "handler": "static_response",
                                        "status_code": 302,
                                        "headers": {"Location": [login]},
                                    }
                                ]
                            }
                        ],
                    },
                    {
                        "match": {"status_code": [2]},
                        "routes": [
                            {"handle": [{"handler": "vars"}]},
                            {
                                "handle": [
                                    {"handler": "headers", "request": {"delete": ["X-Tg-User"]}}
                                ]
                            },
                            {
                                "match": [
                                    {
                                        "not": [
                                            {
                                                "vars": {
                                                    "{http.reverse_proxy.header.X-Tg-User}": [""]
                                                }
                                            }
                                        ]
                                    }
                                ],
                                "handle": [
                                    {
                                        "handler": "headers",
                                        "request": {
                                            "set": {
                                                "X-Tg-User": [
                                                    "{http.reverse_proxy.header.X-Tg-User}"
                                                ]
                                            }
                                        },
                                    }
                                ],
                            },
                        ],
                    },
                ],
            },
            {
                "handler": "reverse_proxy",
                "flush_interval": -1,
                "upstreams": [{"dial": f"{spec.bind_address}:{spec.port}"}],
                "headers": {
                    "request": {
                        "set": {
                            "Host": ["{http.request.host}"],
                            "X-Real-IP": ["{http.request.remote.host}"],
                            "X-Forwarded-Host": ["{http.request.host}"],
                            "X-Forwarded-Proto": ["{http.request.scheme}"],
                            "X-Tg-Router": [spec.router_id],
                        }
                    }
                },
            },
        ],
        "terminal": True,
    }


# --------------------------------------------------------------------------- file helpers
def _write_atomic(path: Path, content: str, mode: int = 0o640) -> None:
    """Write atomically in the same directory: tmp file + os.replace.

    os.replace is atomic on POSIX, so nginx either sees the old config or the new one -
    never a truncated file. The tmp file is created next to the target (never in /tmp) so
    the replace stays on one filesystem and cannot fail with EXDEV.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        dir=str(path.parent), prefix="." + path.name + ".", suffix=".tmp"
    )
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        with contextlib.suppress(OSError):
            os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(FileNotFoundError):
            tmp.unlink()
        raise


def _needs_write(path: Path, content: str) -> bool:
    """True when the file is missing or holds different bytes (sha256 compare)."""
    try:
        current = path.read_bytes()
    except OSError:
        return True
    return hashlib.sha256(current).digest() != hashlib.sha256(content.encode()).digest()


async def run_command(command: str, timeout: float) -> tuple[int, str]:
    """Run a shell command with a hard timeout; returns (exit code, combined output)."""
    proc = await asyncio.create_subprocess_shell(
        command,
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
    )
    try:
        async with asyncio.timeout(timeout):
            out, _ = await proc.communicate()
    except TimeoutError:
        with contextlib.suppress(ProcessLookupError):
            proc.kill()
        with contextlib.suppress(Exception):
            await proc.wait()
        raise ProxyError(f"command timed out after {timeout:g}s: {command}") from None
    return proc.returncode, out.decode("utf-8", "replace").strip()


# --------------------------------------------------------------------------- manager
class ProxyManager:
    """Keeps the reverse proxy's published routes in sync with the database.

    startup() is called once from the app lifespan, reload() right after it (that is the
    initial sync), sync_routes(db) on every monitor cycle. All three are idempotent and
    swallow their own errors into last_error.
    """

    def __init__(self, settings=None, *, caddy_transport: httpx.AsyncBaseTransport | None = None):
        self._settings = settings
        self._lock = asyncio.Lock()
        self._caddy_transport = caddy_transport
        self._reload_pending = False
        self._started = False
        self._routes = 0
        self._last_sync_at = None
        self._last_reload_at = None
        self._last_changed_at = None
        self.last_error: str | None = None

    # ------------------------------------------------------------------ public API
    @property
    def settings(self):
        return self._settings or get_settings()

    @property
    def driver(self) -> str:
        return (self.settings.proxy_driver or "none").strip().lower()

    async def startup(self) -> None:
        """One-time preparation: directories plus placeholder files.

        nginx refuses to start if an include target is missing, so both generated files are
        seeded here, before the first sync and before any reload is attempted.
        """
        s = self.settings
        try:
            Path(s.proxy_routes_path).parent.mkdir(parents=True, exist_ok=True)
        except OSError as exc:  # pragma: no cover - permissions are an operator problem
            self.last_error = f"cannot create proxy config directory: {exc}"
            log.warning("%s", self.last_error)
            return
        if self.driver == "nginx":
            routes_path = Path(s.proxy_routes_path)
            for path in (routes_path, auth_snippet_path(routes_path)):
                if not path.exists():
                    try:
                        _write_atomic(path, f"{GENERATED_MARKER} - DO NOT EDIT.\n")
                    except OSError as exc:  # pragma: no cover
                        self.last_error = f"cannot seed {path}: {exc}"
                        log.warning("%s", self.last_error)
        self._started = True

    async def reload(self) -> bool:
        """Full sync from the database, then reload the proxy if the routes changed."""
        return await self.sync_routes(None)

    async def sync_routes(self, db=None) -> bool:
        """Reconcile the proxy with the DB. Returns True when the published set changed."""
        async with self._lock:
            try:
                changed = await self._sync(db)
            except Exception as exc:  # never raise into the monitor loop
                self.last_error = f"{type(exc).__name__}: {exc}"
                log.warning("proxy sync failed (driver=%s): %s", self.driver, self.last_error)
                return False
            self.last_error = None
            self._last_sync_at = utcnow()
            if changed:
                self._last_changed_at = self._last_sync_at
            return changed

    async def sync(self, db=None) -> bool:
        """Alias used by the monitor (proxy.sync(db))."""
        return await self.sync_routes(db)

    def info(self) -> dict[str, Any]:
        """Snapshot for GET /api/v1/stats / diagnostics."""
        return {
            "driver": self.driver,
            "routes": self._routes,
            "last_error": self.last_error,
            "reload_pending": self._reload_pending,
            "last_sync_at": self._last_sync_at,
            "last_reload_at": self._last_reload_at,
            "last_changed_at": self._last_changed_at,
            "routes_path": str(self.settings.proxy_routes_path),
        }

    # ------------------------------------------------------------------ internals
    async def _sync(self, db) -> bool:
        driver = self.driver
        if driver == "none":
            self._routes = 0
            return False
        specs = load_routes(db) if db is not None else self._load_routes_standalone()
        if driver == "nginx":
            return await self._sync_nginx(specs)
        if driver == "caddy":
            return await self._sync_caddy(specs)
        raise ProxyError(f"unknown TUNNELGATE_PROXY_DRIVER {driver!r} (use nginx|caddy|none)")

    def _load_routes_standalone(self) -> list[RouteSpec]:
        """Open a short-lived session when the caller did not pass one (main.py reload)."""
        from ..db import session_scope

        with session_scope() as session:
            return load_routes(session)

    # -- nginx -----------------------------------------------------------------
    async def _sync_nginx(self, specs: list[RouteSpec]) -> bool:
        s = self.settings
        routes_path = Path(s.proxy_routes_path)
        snippet_path = auth_snippet_path(routes_path)

        rendered = render_nginx(specs, s)
        snippet = render_nginx_auth_snippet(s)

        # Snippet first: a vhost that includes it must never be published before the file
        # exists, or nginx fails the reload and keeps serving the previous fleet config.
        wrote_snippet = False
        if _needs_write(snippet_path, snippet):
            _write_atomic(snippet_path, snippet)
            wrote_snippet = True

        wrote_routes = False
        if _needs_write(routes_path, rendered):
            _write_atomic(routes_path, rendered)
            wrote_routes = True

        self._routes = len(specs)
        changed = wrote_snippet or wrote_routes
        if changed or self._reload_pending:
            await self._reload_nginx()
        return changed

    async def _reload_nginx(self) -> None:
        command = (self.settings.proxy_reload_command or "").strip()
        if not command:
            # Nothing to run: the operator reloads nginx out of band (or a watcher does).
            self._reload_pending = False
            return
        self._reload_pending = True
        code, output = await run_command(command, _reload_timeout(self.settings))
        if code != 0:
            raise ProxyError(f"reload command exited {code}: {command}: {output[:400]}")
        self._reload_pending = False
        self._last_reload_at = utcnow()
        log.info("proxy routes reloaded (%d routers)", self._routes)

    # -- caddy -----------------------------------------------------------------
    async def _caddy_request(
        self, client: httpx.AsyncClient, method: str, path: str, payload: Any = None
    ) -> httpx.Response:
        base = str(self.settings.caddy_admin_url).rstrip("/")
        url = base + path
        try:
            response = await client.request(
                method,
                url,
                json=payload,
                headers={"Origin": base},
            )
        except httpx.HTTPError as exc:
            raise ProxyError(f"caddy admin API unreachable at {url}: {exc}") from exc
        if response.status_code >= 400:
            raise ProxyError(
                f"caddy {method} {path} -> {response.status_code}: {response.text[:300]}"
            )
        return response

    async def _sync_caddy(self, specs: list[RouteSpec]) -> bool:
        s = self.settings
        server = str(s.caddy_server or "srv0")
        base = f"/config/apps/http/servers/{quote(server, safe='')}"
        desired = {
            f"{CADDY_ROUTE_PREFIX}{spec.router_id}": render_caddy_route(spec, s) for spec in specs
        }
        changed = False

        async with httpx.AsyncClient(transport=self._caddy_transport, timeout=10.0) as client:
            # The server object must exist before routes can be attached to it.
            try:
                current = (await self._caddy_request(client, "GET", base)).json()
            except ProxyError as exc:
                if "-> 404" not in str(exc):
                    raise
                log.info("caddy server %r missing, creating it", server)
                await self._caddy_request(
                    client,
                    "PUT",
                    base,
                    {
                        "listen": [":443"],
                        "routes": [],
                        "automatic_https": {"disable_redirects": False},
                    },
                )
                current = {"routes": []}
                changed = True

            existing: list[dict[str, Any]] = current.get("routes") or []
            by_id = {
                str(route.get("@id")): route
                for route in existing
                if isinstance(route, dict)
                and str(route.get("@id", "")).startswith(CADDY_ROUTE_PREFIX)
            }

            for route_id, route in desired.items():
                previous = by_id.pop(route_id, None)
                if previous is not None and _same_json(previous, route):
                    continue
                if previous is None:
                    await self._caddy_request(client, "POST", f"{base}/routes", route)
                else:
                    await self._caddy_request(
                        client, "PUT", f"/id/{quote(route_id, safe='')}", route
                    )
                changed = True

            # Whatever is left under our namespace is a stale router (deleted, revoked or
            # re-slugged): remove it so the public hostname stops resolving to a dead tunnel.
            for stale_id in by_id:
                await self._caddy_request(client, "DELETE", f"/id/{quote(stale_id, safe='')}")
                changed = True

        self._routes = len(specs)
        if changed:
            self._last_reload_at = utcnow()  # the admin API applied it synchronously
            log.info("caddy routes synced (%d routers)", self._routes)
        return changed


def _same_json(left: Any, right: Any) -> bool:
    """Order-insensitive structural comparison for Caddy route objects."""
    return json.dumps(left, sort_keys=True) == json.dumps(right, sort_keys=True)
